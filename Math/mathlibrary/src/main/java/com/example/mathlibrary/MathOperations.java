package com.example.mathlibrary;

public class MathOperations {
    public static int sum(int a, int b) {
        return a + b;
    }

    // Método para restar
    public static int subtract(int a, int b) {
        return a - b;
    }

    // Método para multiplicar
    public static int multiply(int a, int b) {
        return a * b;
    }
}
